def write_csv(path, items, headers):
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=headers, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(items)

def write_json(path, items):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False, indent=2)

def save_dual(filename_stem, items, headers):
    csv_name = f"{filename_stem}.csv"
    json_name = f"{filename_stem}.json"
    write_csv(DIST / csv_name, items, headers)
    write_json(DIST / json_name, items)
    write_csv(DIST_WB / csv_name, items, headers)
    write_json(DIST_WB / json_name, items)
    print(f"  -> Exported {filename_stem}: {len(items)} records (CSV & JSON)")

